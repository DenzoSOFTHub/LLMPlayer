__device__ __forceinline__ float iq2xxs_h2f(unsigned short h) {
    float r;
    asm("cvt.f32.f16 %0, %1;" : "=f"(r) : "h"(h));
    return r;
}

__device__ __forceinline__ unsigned int iq2xxs_u32(const unsigned char* __restrict__ p) {
    const unsigned short* s = (const unsigned short*) p;
    return (unsigned int) __ldg(s) | ((unsigned int) __ldg(s + 1) << 16);
}

extern "C" __global__ void matmul_iq2_xxs(
    const unsigned char* __restrict__ weights, const float* __restrict__ input, float* __restrict__ output,
    const int rows, const int cols, const int addToOutput)
{
    // 8 lanes per group of 32 weights, 4 weights per lane, coalesced float4 input reads
    // (see matmul_iq1_m).
    int lane = threadIdx.x & 31;
    int row = blockIdx.x * (blockDim.x / 32) + threadIdx.x / 32;
    if (row >= rows) return;
    int ngroups = (cols / 256) * 8;
    long rowBase = (long) row * (cols / 256) * 66;
    int sub = lane & 7, l = sub >> 1, hi = sub & 1;
    float sum = 0.0f;
    for (int g = lane >> 3; g < ngroups; g += 4) {
        int sb = g >> 3, ib = g & 7;
        long bo = rowBase + (long) sb * 66;
        float d = iq2xxs_h2f(__ldg((const unsigned short*) (weights + bo)));
        unsigned int a1 = iq2xxs_u32(weights + bo + 6 + 8 * ib);
        float db = d * (0.5f + (float) (a1 >> 28)) * 0.25f;
        unsigned int gi = __ldg(weights + bo + 2 + 8 * ib + l);
        unsigned int q = (unsigned int) (__ldg(&IQ2XXS_GRID[gi]) >> (32 * hi));
        unsigned int sg = __ldg(&KSIGNS_IQ2XS_C[(a1 >> (7 * l)) & 127]) >> (4 * hi);
        float4 xv = __ldg((const float4*) (input + g * 32 + sub * 4));
        float v0 = (float) (q & 0xFF), v1 = (float) ((q >> 8) & 0xFF);
        float v2 = (float) ((q >> 16) & 0xFF), v3 = (float) (q >> 24);
        sum += db * (((sg & 1) ? -v0 : v0) * xv.x + ((sg & 2) ? -v1 : v1) * xv.y
                   + ((sg & 4) ? -v2 : v2) * xv.z + ((sg & 8) ? -v3 : v3) * xv.w);
    }
    for (int off = 16; off > 0; off >>= 1) sum += __shfl_down_sync(0xFFFFFFFF, sum, off);
    if (lane == 0) output[row] = addToOutput ? output[row] + sum : sum;
}

// FP16 row-range dequantization for the batched prefill GEMM (see dequant_f16.cu for the contract).
extern "C" __global__ void dequant_iq2_xxs_f16t(const unsigned char* __restrict__ w, unsigned short* __restrict__ out,
                                                int rowStart, int nRows, int cols) {
    long idx = (long) blockIdx.x * blockDim.x + threadIdx.x;
    if (idx >= (long) nRows * cols) return;
    int rr = (int) (idx / cols), col = (int) (idx - (long) rr * cols);
    long bo = ((long) rowStart + rr) * (cols / 256) * 66 + (long) (col / 256) * 66;
    int j = col & 255, ib = j >> 5, l = (j >> 3) & 3, jj = j & 7;
    float d = iq2xxs_h2f((unsigned short) (w[bo] | (w[bo + 1] << 8)));
    const unsigned char* q = w + bo + 2 + 8 * ib;
    unsigned int a1 = q[4] | (q[5] << 8) | (q[6] << 16) | ((unsigned int) q[7] << 24);
    float db = d * (0.5f + (float) (a1 >> 28)) * 0.25f;
    float v = db * (float) ((__ldg(&IQ2XXS_GRID[q[l]]) >> (8 * jj)) & 0xFF);
    if ((__ldg(&KSIGNS_IQ2XS_C[(a1 >> (7 * l)) & 127]) >> jj) & 1) v = -v;
    unsigned short o; asm("cvt.rn.f16.f32 %0, %1;" : "=h"(o) : "f"(v));
    out[idx] = o;
}
